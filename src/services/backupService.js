import { query } from '../db/pool.js';

function quotePgIdentifier(name) {
    return `"${String(name).replace(/"/g, '""')}"`;
}

function formatPgValue(val) {
    if (val === null || val === undefined) return 'NULL';
    if (typeof val === 'boolean') return val ? 'TRUE' : 'FALSE';
    if (typeof val === 'number') return Number.isFinite(val) ? String(val) : 'NULL';
    if (val instanceof Date) return `'${val.toISOString().replace(/'/g, "''")}'`;
    if (typeof val === 'object') return `'${JSON.stringify(val).replace(/'/g, "''")}'`;
    return `'${String(val).replace(/'/g, "''")}'`;
}

export async function generatePostgresBackupSql(adminUser) {
    const { rows: tableRows } = await query(
        `SELECT tablename FROM pg_tables
         WHERE schemaname = 'public'
           AND tablename NOT IN ('sessions', 'password_reset_tokens')
         ORDER BY tablename`
    );

    const lines = [
        '-- E-Barangay System PostgreSQL Database Backup',
        `-- Generated at: ${new Date().toISOString()}`,
        `-- Generated by: ${adminUser?.name || 'Admin'} (${adminUser?.email || ''})`,
        '',
        'BEGIN;',
        '',
    ];

    for (const { tablename } of tableRows) {
        const quotedTable = quotePgIdentifier(tablename);
        const { rows } = await query(`SELECT * FROM ${quotedTable}`);
        lines.push(`-- Table: ${tablename} (${rows.length} rows)`);
        if (rows.length > 0) {
            const cols = Object.keys(rows[0]).map(quotePgIdentifier).join(', ');
            for (const row of rows) {
                const vals = Object.values(row).map(formatPgValue).join(', ');
                lines.push(`INSERT INTO ${quotedTable} (${cols}) VALUES (${vals}) ON CONFLICT DO NOTHING;`);
            }
        }
        lines.push('');
    }

    lines.push('COMMIT;');
    return lines.join('\n');
}
